// Compiles src/tui.tsx to dist/tui.js with OpenTUI's Solid JSX transform.
//
// OpenTUI compiles plugin JSX itself, except under node_modules: an installed
// copy of this package would get the default (React) JSX. The committed
// dist/tui.js is plain ESM that OpenTUI's runtime plugin can load from
// node_modules; it imports the other modules from ../src/*.ts.
//
// Same Babel presets as @opentui/solid/scripts/solid-transform.js.
//
//   node scripts/build-tui.mjs           writes dist/tui.js
//   node scripts/build-tui.mjs --print   prints it instead (used by the tests)
import { transformAsync } from "@babel/core"
import ts from "@babel/preset-typescript"
import solid from "babel-preset-solid"
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const source = join(root, "src", "tui.tsx")
const output = join(root, "dist", "tui.js")

const HEADER = "// Generated by scripts/build-tui.mjs from src/tui.tsx: do not edit, run `npm run build`.\n"

/** `./sync` → `../src/sync.ts`: dist/tui.js runs the TypeScript sources next to it. */
function rewriteRelative() {
  const rewrite = (node) => {
    const value = node?.value
    if (typeof value !== "string" || !value.startsWith("./")) return
    node.value = `../src/${value.slice(2).replace(/\.tsx?$/, "")}.ts`
  }
  return {
    visitor: {
      ImportDeclaration: (path) => rewrite(path.node.source),
      ExportNamedDeclaration: (path) => rewrite(path.node.source),
      ExportAllDeclaration: (path) => rewrite(path.node.source),
    },
  }
}

export async function buildTui() {
  const result = await transformAsync(readFileSync(source, "utf8"), {
    filename: source,
    configFile: false,
    babelrc: false,
    plugins: [rewriteRelative],
    presets: [[solid, { moduleName: "@opentui/solid", generate: "universal" }], [ts]],
  })
  if (!result?.code) throw new Error("babel produced no code")
  return `${HEADER}${result.code}\n`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const code = await buildTui()
  if (process.argv.includes("--print")) process.stdout.write(code)
  else {
    mkdirSync(dirname(output), { recursive: true })
    writeFileSync(output, code)
  }
}
